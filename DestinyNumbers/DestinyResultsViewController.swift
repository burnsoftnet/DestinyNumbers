import UIKit

class DestinyResultsViewController: UIViewController {

    var pushMeaning = ""
    var yourNumber = ""
    @IBOutlet weak var lblTitle: UILabel!
    @IBOutlet weak var txtMeaning: UITextView!

    // MARK: View Did Load
    //When the View first Appears
    override func viewDidLoad() {
        super.viewDidLoad()
        lblTitle.text = yourNumber
        txtMeaning.text = pushMeaning

        let actionButton = UIBarButtonItem(barButtonSystemItem: .action, target: self, action: #selector(startAction(_:)))
        navigationItem.rightBarButtonItems = [actionButton]

        setBackGroundImage()
    }

    // MARK: View Did Layout Subviews
    //when the screen is reorientated to another angle
    override func viewDidLayoutSubviews() {
        super.viewDidLayoutSubviews()
        setBackGroundImage()
    }

    // MARK: Set Background Image
    //set the background image of the view
    private func setBackGroundImage() {
        view.backgroundColor = UIColor.backgroundPattern(for: view)
    }

    // MARK: Start Action Sheet
    //start the action sheet process and gather the data to send to the share sheet
    @objc private func startAction(_ sender: UIBarButtonItem) {
        let rawText = "\(yourNumber)\n\n \(pushMeaning)\n\n\n\nGenerated by the Destiny Numbers App for iOS"

        let controller = UIActivityViewController(activityItems: [rawText], applicationActivities: nil)
        controller.setValue("\(yourNumber)!", forKey: "subject")

        // On iPad the activity view controller is shown in a popover anchored to the share button.
        controller.popoverPresentationController?.sourceItem = sender
        controller.popoverPresentationController?.permittedArrowDirections = .any

        present(controller, animated: true)
    }
}
